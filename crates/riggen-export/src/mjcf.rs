    /// The element, the gains and the two ranges each preset writes — and
    /// the two zeros that mean "nobody filled this in" rather than "clamp
    /// it to zero" (ADR-0014). The golden above covers the third case, a
    /// `Continuous` joint, whose missing `Limits` leave both ranges out.
    #[test]
    fn each_preset_writes_its_element_with_ctrlrange_and_forcerange() {
        /// The `<actuator>` line for `upper_joint`, alone in the block.
        fn line(actuator: ActuatorSpec, effort: f64, velocity: f64) -> String {
            let mut b = every_joint_kind();
            // Only `upper_joint` is driven here, whatever `every_joint_kind`
            // set up: the line under test must be alone in the block.
            b.robot.actuators.clear();
            let mut driven = None;
            for (&id, j) in b.robot.joints.iter_mut() {
                let hinge = j.name == "upper_joint";
                if hinge {
                    driven = Some(id);
                    // Only the two ranges vary: moving `lower`/`upper`
                    // would move the slider's mimic reach with them.
                    j.limits = Some(Limits {
                        lower: -1.0,
                        upper: 1.0,
                        effort,
                        velocity,
                    });
                }
            }
            b.actuator(driven.expect("upper_joint is in the chain"), actuator);
            let xml = write(&b.resolve().unwrap(), &ExportOptions::default());
            assert!(
                !xml.contains("joint upper_joint: effort"),
                "an actuated joint keeps no apology (ADR-0004 §4 as amended)\n{xml}"
            );
            assert!(
                xml.contains("joint slider_joint: effort"),
                "one with no actuator still does\n{xml}"
            );
            xml.lines()
                .find(|l| l.contains(r#"joint="upper_joint""#))
                .unwrap_or_default()
                .trim()
                .to_owned()
        }

        assert_eq!(
            line(ActuatorSpec::Position { kp: 100.0, kv: 5.0 }, 2.0, 3.0),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrlrange="-1 1" forcerange="-2 2"/>"#
        );
        // A velocity servo is commanded in the joint's own rate, so its
        // `ctrlrange` is the velocity limit, not the position one.
        assert_eq!(
            line(ActuatorSpec::Velocity { kv: 2.0 }, 2.0, 3.0),
            r#"<velocity name="upper_joint" joint="upper_joint" kv="2" ctrlrange="-3 3" forcerange="-2 2"/>"#
        );
        // A motor's `ctrl` is normalised; `gear` is what scales it.
        assert_eq!(
            line(ActuatorSpec::Motor { gear: 50.0 }, 2.0, 3.0),
            r#"<motor name="upper_joint" joint="upper_joint" gear="50" ctrlrange="-1 1" forcerange="-2 2"/>"#
        );
        // `effort` 0 is the unfilled value: no `forcerange`, so
        // `autolimits` leaves the force unbounded — MuJoCo's own default —
        // rather than clamping it to zero. Same for `velocity` 0.
        assert_eq!(
            line(ActuatorSpec::Position { kp: 100.0, kv: 5.0 }, 0.0, 3.0),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrlrange="-1 1"/>"#
        );
        assert_eq!(
            line(ActuatorSpec::Velocity { kv: 2.0 }, 0.0, 0.0),
            r#"<velocity name="upper_joint" joint="upper_joint" kv="2"/>"#
        );
        // The escape hatch (ADR-0024): the three type names, each `prm`
        // vector trimmed of the zeros MuJoCo would fill in — but not
        // emptied — and `gear` like a motor's. No preset means no derived
        // `ctrlrange`; `forcerange` still follows the joint's effort.
        let general = |dynprm: Vec<f64>, gainprm: Vec<f64>, biasprm: Vec<f64>| {
            ActuatorSpec::General(General {
                dyntype: DynType::Filter,
                gaintype: GainType::Fixed,
                biastype: BiasType::Affine,
                dynprm,
                gainprm,
                biasprm,
                gear: 2.0,
            })
        };
        assert_eq!(
            line(
                general(
                    vec![0.1],
                    vec![200.0, 0.0, 0.0],
                    vec![0.0, -200.0, -5.0, 0.0]
                ),
                2.0,
                3.0
            ),
            r#"<general name="upper_joint" joint="upper_joint" dyntype="filter" gaintype="fixed" biastype="affine" dynprm="0.1" gainprm="200" biasprm="0 -200 -5" gear="2" forcerange="-2 2"/>"#
        );
        assert_eq!(
            line(general(vec![0.0, 0.0], Vec::new(), vec![0.0]), 0.0, 0.0),
            r#"<general name="upper_joint" joint="upper_joint" dyntype="filter" gaintype="fixed" biastype="affine" dynprm="0" biasprm="0" gear="2"/>"#,
            "an all-zero vector keeps one zero: absent would mean MuJoCo's default"
        );
        assert_eq!(
            line(ActuatorSpec::General(General::default()), 0.0, 0.0),
            r#"<general name="upper_joint" joint="upper_joint" dyntype="none" gaintype="fixed" biastype="none" gear="1"/>"#
        );
    }

    /// The ranges are the actuator's own, else the joint's (ADR-0024): what
    /// an imported file said comes back out as it was said, flags
    /// included, and only a riggen-authored actuator — every field `None`
    /// — has its ranges derived. `Some(false)` beside no range is the
    /// imported `<position>` that named no `ctrlrange`: unlimited, not
    /// clamped to the joint.
    #[test]
    fn an_actuators_own_ranges_win_over_the_joints_and_the_flags_are_explicit() {
        fn line(ranges: ActuatorRanges) -> String {
            let mut b = every_joint_kind();
            let driven = b.robot.joints.iter().find(|(_, j)| j.name == "upper_joint");
            let driven = *driven.expect("upper_joint is in the chain").0;
            b.robot.actuators.clear();
            let id = b.actuator(driven, ActuatorSpec::Position { kp: 100.0, kv: 5.0 });
            b.robot.actuators.get_mut(&id).unwrap().ranges = ranges;
            let xml = write(&b.resolve().unwrap(), &ExportOptions::default());
            xml.lines()
                .find(|l| l.contains("joint=\"upper_joint\""))
                .map(str::trim)
                .unwrap()
                .to_owned()
        }
        // Nothing said: the joint's range and effort, as always.
        assert_eq!(
            line(ActuatorRanges::default()),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrlrange="-1 1" forcerange="-1 1"/>"#
        );
        // A narrower `ctrlrange` than the joint's, and a `forcerange` the
        // joint's effort does not agree with: the file's numbers stand.
        assert_eq!(
            line(ActuatorRanges {
                ctrl: Some([-0.5, 0.25]),
                force: Some([-30.0, 30.0]),
                ctrl_limited: None,
                force_limited: None,
            }),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrlrange="-0.5 0.25" forcerange="-30 30"/>"#
        );
        // The file named no `ctrlrange` under `autolimits`: unlimited, so
        // the joint's range must not be invented for it. The effort still
        // derives, since nothing was said about force.
        assert_eq!(
            line(ActuatorRanges {
                ctrl_limited: Some(false),
                ..ActuatorRanges::default()
            }),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrllimited="false" forcerange="-1 1"/>"#
        );
        // An explicit flag is written explicitly, beside its range — and
        // a `false` beside a range keeps the range, as MuJoCo does.
        assert_eq!(
            line(ActuatorRanges {
                ctrl: Some([-1.0, 1.0]),
                force: Some([-2.0, 2.0]),
                ctrl_limited: Some(true),
                force_limited: Some(false),
            }),
            r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrllimited="true" ctrlrange="-1 1" forcelimited="false" forcerange="-2 2"/>"#
        );
    }

    /// The two things `Joint::actuator` could not say (ADR-0023): an
    /// element under a name that is not its joint's, and two elements
    /// driving one joint. Both are what MJCF itself allows — namespaces are
    /// per element type, and MuJoCo sums the controls of every actuator on
    /// a joint — so both must come out of the writer as the document holds
    /// them.
    #[test]
    fn an_actuator_writes_its_own_name_and_a_joint_may_have_two() {
        let mut b = every_joint_kind();
        let wheel = *b
            .robot
            .joints
            .iter()
            .find(|(_, j)| j.name == "wheel_joint")
            .unwrap()
            .0;
        b.named_actuator("wheel_boost", wheel, ActuatorSpec::Motor { gear: 5.0 });
        let xml = write(&b.resolve().unwrap(), &ExportOptions::default());

        // By the trimmed line, not by `contains`: the apologetic comment
        // says "need an <actuator>" too.
        let block: Vec<&str> = xml
            .lines()
            .map(str::trim)
            .skip_while(|l| *l != "<actuator>")
            .skip(1)
            .take_while(|l| *l != "</actuator>")
            .collect();
        assert_eq!(
            block,
            [
                r#"<position name="upper_joint" joint="upper_joint" kp="100" kv="5" ctrlrange="-1 1" forcerange="-1 1"/>"#,
                r#"<velocity name="wheel_joint" joint="wheel_joint" kv="2"/>"#,
                r#"<motor name="wheel_boost" joint="wheel_joint" gear="5" ctrlrange="-1 1"/>"#,
            ],
            "in ActuatorId order, each under its own name\n{xml}"
        );
        // And the apology stays off a joint that any actuator drives — the
        // second one does not make it true again (ADR-0004 §4).
        assert!(!xml.contains("joint wheel_joint: effort"), "{xml}");
    }

