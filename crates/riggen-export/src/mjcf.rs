//! The MJCF writer (docs/02-data-model.md §Format mapping, ADR-0004,
//! ADR-0008): nested `<body>`s in the resolved order, one `<joint>` per
//! movable edge inside the child body, `<inertial pos mass fullinertia>`
//! so MuJoCo does the principal-axes decomposition itself, meshes by stem
//! under `meshdir="meshes"`.

use riggen_core::glam::DVec3;
use riggen_core::{ActuatorSpec, JointKind, Pose, Primitive};

use crate::resolve::{ExportOptions, ResolvedActuator, ResolvedGeom, ResolvedJoint, ResolvedRobot};
use crate::xml::{Xml, num, quat, vec3};

/// The translucent orange of the unirobot example's collision class.
pub const COLLISION_RGBA: &str = "0.9 0.4 0.1 0.25";

pub fn write(robot: &ResolvedRobot, _options: &ExportOptions) -> String {
    let mut x = Xml::new();
    x.open("mujoco", &[("model", robot.name.clone())]);
    x.comment("Generated by riggen. Meshes are in meters (ADR-0008).");
    x.empty(
        "compiler",
        &[
            ("angle", "radian".into()),
            ("meshdir", "meshes".into()),
            ("autolimits", "true".into()),
        ],
    );

    x.open("default", &[]);
    x.open("default", &[("class", "visual".into())]);
    x.empty(
        "geom",
        &[
            ("type", "mesh".into()),
            ("contype", "0".into()),
            ("conaffinity", "0".into()),
            ("group", "2".into()),
        ],
    );
    x.close("default");
    x.open("default", &[("class", "collision".into())]);
    x.empty(
        "geom",
        &[("group", "3".into()), ("rgba", COLLISION_RGBA.into())],
    );
    x.close("default");
    x.close("default");

    if !robot.meshes.is_empty() {
        x.open("asset", &[]);
        for name in robot.meshes.keys() {
            x.empty(
                "mesh",
                &[("name", name.clone()), ("file", format!("{name}.stl"))],
            );
        }
        x.close("asset");
    }

    x.open("worldbody", &[]);
    if !robot.links.is_empty() {
        write_body(&mut x, robot, 0);
    }
    x.close("worldbody");

    // MJCF has no `<mimic>`: a coupled DoF is a solver equality, and
    // `polycoef` is `y - y0 = a0 + a1(x - x0) + …` over the two joints'
    // deviations from `qpos0`. We never write `ref`, so both references
    // are zero and `(offset, multiplier, 0, 0, 0)` is exactly URDF's rule
    // (ADR-0013). It is a *soft* constraint, not a reduction.
    if robot.joints.iter().any(|j| j.mimic.is_some()) {
        x.open("equality", &[]);
        for j in &robot.joints {
            let Some(m) = &j.mimic else { continue };
            x.empty(
                "joint",
                &[
                    ("joint1", j.name.clone()),
                    ("joint2", robot.joints[m.joint].name.clone()),
                    (
                        "polycoef",
                        format!("{} {} 0 0 0", num(m.offset), num(m.multiplier)),
                    ),
                ],
            );
        }
        x.close("equality");
    }

    // One element per actuator, under its own name (ADR-0023): MJCF
    // namespaces are per element type, so `model.actuator("shoulder")` and
    // `model.joint("shoulder")` coexist — and the default name is the
    // joint's, so `data.ctrl` stays indexable by the name the user already
    // knows unless a file said otherwise.
    if !robot.actuators.is_empty() {
        x.open("actuator", &[]);
        for a in &robot.actuators {
            write_actuator(&mut x, a, &robot.joints[a.joint]);
        }
        x.close("actuator");
    }

    x.close("mujoco");
    x.finish()
}

fn write_body(x: &mut Xml, robot: &ResolvedRobot, index: usize) {
    let link = &robot.links[index];
    let joint = robot.parent_joint(index);
    let mut attrs = vec![("name", link.name.clone())];
    if let Some(j) = joint {
        attrs.extend(pose_attrs(&j.origin));
    }
    x.open("body", &attrs);

    if index == 0 && robot.floating_base {
        x.empty("freejoint", &[("name", "root".into())]);
    }
    if let Some(j) = joint.filter(|j| j.kind.is_movable()) {
        // `joints[index - 1]` is `links[index]`'s parent joint.
        let driven = robot.actuators_on(index - 1).next().is_some();
        write_joint(x, j, driven);
    }
    if let Some(i) = &link.inertial {
        let m = &i.inertia;
        x.empty(
            "inertial",
            &[
                ("pos", vec3(i.com)),
                ("mass", num(i.mass)),
                (
                    "fullinertia",
                    // MuJoCo's order: Ixx Iyy Izz Ixy Ixz Iyz.
                    format!(
                        "{} {} {} {} {} {}",
                        num(m.x_axis.x),
                        num(m.y_axis.y),
                        num(m.z_axis.z),
                        num(m.y_axis.x),
                        num(m.z_axis.x),
                        num(m.z_axis.y)
                    ),
                ),
            ],
        );
    }
    for geom in &link.visuals {
        write_geom(x, "visual", geom);
    }
    for geom in &link.collisions {
        write_geom(x, "collision", geom);
    }
    // A frame is a bare `<site>` at the class defaults (ADR-0012): no
    // `size`, no `group`, so MuJoCo's own 0.005 m sphere renders it as a
    // visible marker and an override is a `<default>` the user adds.
    for site in &link.sites {
        let mut attrs = vec![("name", site.name.clone())];
        attrs.extend(pose_attrs(&site.pose));
        x.empty("site", &attrs);
    }
    for child in robot.child_joints(index) {
        write_body(x, robot, child.child);
    }
    x.close("body");
}

fn write_joint(x: &mut Xml, j: &ResolvedJoint, driven: bool) {
    let mut attrs = vec![
        ("name", j.name.clone()),
        (
            "type",
            match j.kind {
                JointKind::Prismatic => "slide",
                _ => "hinge",
            }
            .into(),
        ),
        ("axis", vec3(j.axis)),
    ];
    if let Some(l) = &j.limits {
        attrs.push(("range", format!("{} {}", num(l.lower), num(l.upper))));
    }
    let d = &j.dynamics;
    if d.damping != 0.0 {
        attrs.push(("damping", num(d.damping)));
    }
    if d.friction != 0.0 {
        attrs.push(("frictionloss", num(d.friction)));
    }
    if d.armature != 0.0 {
        attrs.push(("armature", num(d.armature)));
    }
    x.empty("joint", &attrs);
    // ADR-0004 §4, as amended by ADR-0014 and re-keyed by ADR-0023: what
    // MJCF cannot hold without an actuator is named, not dropped — but only
    // while **no** actuator targets the joint, or the apology would be a
    // lie beside the `<actuator>` a few lines down.
    if let Some(l) = j.limits.filter(|_| !driven) {
        x.comment(&format!(
            "joint {}: effort {} velocity {} need an <actuator>; not written",
            j.name,
            num(l.effort),
            num(l.velocity)
        ));
    }
}

/// One `<position>` / `<velocity>` / `<motor>` / `<general>`: `a` under
/// its own name, driving `j` (ADR-0014, ADR-0023, ADR-0024).
///
/// A `<general>` writes its three type names, its `prm` vectors with the
/// zeros MuJoCo would fill in trimmed off the end — `gainprm="200"`, not
/// ten numbers — and its `gear`, the way a `<motor>` does. It has no
/// preset to derive a `ctrlrange` from, so only what the file said is
/// written; MuJoCo's default is unlimited.
///
/// The ranges are **the actuator's own, else the joint's** (ADR-0024).
/// What the file said — `ResolvedActuator::ranges` — is written as it was
/// said, its `ctrllimited` / `forcelimited` explicit whenever the flag is
/// `Some`; only where it said nothing is a range derived: `ctrlrange` is
/// the joint's own range for a position servo and `±velocity` for a
/// velocity one — both out of `Limits`, so a `Continuous` joint has none —
/// while a motor's `ctrl` is the normalised `-1 1` that `gear` scales, and
/// `forcerange` is `±effort`. A zero `effort` or `velocity` is the
/// *unfilled* value, not a clamp to zero, so its attribute is left out and
/// MuJoCo's own unbounded default stands (`autolimits="true"` then leaves
/// the matching `*limited` off). A flag of `Some(false)` beside no range
/// derives nothing either: the file meant unlimited, and the joint's
/// numbers would clamp what it left open.
fn write_actuator(x: &mut Xml, a: &ResolvedActuator, j: &ResolvedJoint) {
    let pair = |[lo, hi]: [f64; 2]| format!("{} {}", num(lo), num(hi));
    let symmetric = |v: f64| (v != 0.0).then(|| pair([-v, v]));
    let (tag, gains, derived_ctrl) = match &a.spec {
        ActuatorSpec::Position { kp, kv } => (
            "position",
            vec![("kp", num(*kp)), ("kv", num(*kv))],
            j.limits.map(|l| pair([l.lower, l.upper])),
        ),
        ActuatorSpec::Velocity { kv } => (
            "velocity",
            vec![("kv", num(*kv))],
            j.limits.and_then(|l| symmetric(l.velocity)),
        ),
        ActuatorSpec::Motor { gear } => {
            ("motor", vec![("gear", num(*gear))], Some("-1 1".to_owned()))
        }
        ActuatorSpec::General(g) => {
            let mut attrs = vec![
                ("dyntype", g.dyntype.mjcf_name().to_owned()),
                ("gaintype", g.gaintype.mjcf_name().to_owned()),
                ("biastype", g.biastype.mjcf_name().to_owned()),
            ];
            attrs.extend(
                g.prms()
                    .into_iter()
                    .filter_map(|(name, prm)| Some((name, numbers(trimmed(prm))?))),
            );
            attrs.push(("gear", num(g.gear)));
            ("general", attrs, None)
        }
    };
    let derived_force = j.limits.and_then(|l| symmetric(l.effort));
    let own = &a.ranges;
    let range = |said: Option<[f64; 2]>, flag: Option<bool>, derived: Option<String>| {
        said.map(pair)
            .or_else(|| (flag != Some(false)).then_some(derived).flatten())
    };
    let mut attrs = vec![("name", a.name.clone()), ("joint", j.name.clone())];
    attrs.extend(gains);
    for (limited, range) in [
        (
            ("ctrllimited", own.ctrl_limited),
            ("ctrlrange", range(own.ctrl, own.ctrl_limited, derived_ctrl)),
        ),
        (
            ("forcelimited", own.force_limited),
            (
                "forcerange",
                range(own.force, own.force_limited, derived_force),
            ),
        ),
    ] {
        if let Some(flag) = limited.1 {
            attrs.push((limited.0, flag.to_string()));
        }
        if let Some(value) = range.1 {
            attrs.push((range.0, value));
        }
    }
    x.empty(tag, &attrs);
}

/// `prm` with the trailing zeros MuJoCo would fill in anyway left off —
/// but never emptied: `dynprm="0"` means zero where an absent `dynprm`
/// means MuJoCo's default of one.
fn trimmed(prm: &[f64]) -> &[f64] {
    let keep = prm.iter().rposition(|v| *v != 0.0).map_or(0, |i| i + 1);
    &prm[..keep.max(1).min(prm.len())]
}

/// A space-separated attribute value, or `None` for nothing to write.
fn numbers(values: &[f64]) -> Option<String> {
    (!values.is_empty()).then(|| values.iter().map(|v| num(*v)).collect::<Vec<_>>().join(" "))
}

fn write_geom(x: &mut Xml, class: &str, geom: &ResolvedGeom) {
    let mut attrs = vec![("class", class.to_owned())];
    match geom {
        ResolvedGeom::Mesh { name, pose, .. } => {
            if class == "collision" {
                attrs.push(("type", "mesh".into()));
            }
            attrs.push(("mesh", name.clone()));
            attrs.extend(pose_attrs(pose));
        }
        ResolvedGeom::Primitive(p) => {
            // MJCF `size` is half-extents for a box and (radius, half-length)
            // for a cylinder / capsule — the classic mistake, pinned in
            // `primitive_sizes_are_half_extents`.
            let (kind, size, pose) = match p {
                Primitive::Box { pose, size } => ("box", vec3(*size * 0.5), pose),
                Primitive::Cylinder {
                    pose,
                    radius,
                    length,
                } => (
                    "cylinder",
                    format!("{} {}", num(*radius), num(length * 0.5)),
                    pose,
                ),
                Primitive::Sphere { pose, radius } => ("sphere", num(*radius), pose),
                Primitive::Capsule {
                    pose,
                    radius,
                    length,
                } => (
                    "capsule",
                    format!("{} {}", num(*radius), num(length * 0.5)),
                    pose,
                ),
            };
            attrs.push(("type", kind.into()));
            attrs.push(("size", size));
            attrs.extend(pose_attrs(pose));
        }
    }
    x.empty("geom", &attrs);
}

/// `pos` and `quat`, each only when it is not the default.
fn pose_attrs(pose: &Pose) -> Vec<(&'static str, String)> {
    let mut attrs = Vec::new();
    if pose.t != DVec3::ZERO {
        attrs.push(("pos", vec3(pose.t)));
    }
    if quat(pose.r) != "1 0 0 0" {
        attrs.push(("quat", quat(pose.r)));
    }
    attrs
}

