    fn golden_sdf_for_every_joint_kind() {
        let b = every_joint_kind();
        let sdf = write(
            &b.resolve().unwrap(),
            &ExportOptions::default(),
            Path::new("."),
        );
        if sdf != GOLDEN {
            for (i, (a, e)) in sdf.lines().zip(GOLDEN.lines()).enumerate() {
                assert_eq!(a, e, "line {}", i + 1);
            }
            assert_eq!(sdf.lines().count(), GOLDEN.lines().count());
        }
        // Well-formed XML with the shape SDF wants, checked here so a
        // broken nesting fails in `cargo test` and not only in the CI job
        // that runs libsdformat over it (ADR-0016 §6).
        let root = crate::xml::parse(&sdf).unwrap();
        assert_eq!(root.tag, "sdf");
        assert_eq!(root.attr("version"), Some(VERSION));
        let model = root.child("model").unwrap();
        assert_eq!(model.attr("name"), Some("test"));
        assert_eq!(model.kids("link").count(), 5, "five links, flat");
        // The root says nothing about where it is; every other link names
        // its parent, and the chain is the tree (ADR-0016 §2).
        let links: Vec<_> = model.kids("link").collect();
        assert_eq!(links[0].child("pose"), None, "the root has no <pose>");
        for (link, parent) in links[1..]
            .iter()
            .zip(["base_link", "upper", "slider", "wheel"])
        {
            assert_eq!(
                link.child("pose").unwrap().attr("relative_to"),
                Some(parent),
                "{}",
                link.attr("name").unwrap()
            );
        }
        // An empty static link gets no `<inertial>`, as in URDF.
        assert_eq!(links[4].attr("name"), Some("tip"));
        assert_eq!(links[4].child("inertial"), None);
        // Every visual and collision is named, and uniquely inside its
        // link — SDF requires it, and a duplicate is an error there.
        for link in &links {
            let mut names: Vec<&str> = link
                .children
                .iter()
                .filter(|c| c.tag == "visual" || c.tag == "collision")
                .map(|c| c.attr("name").expect("named"))
                .collect();
            let count = names.len();
            names.sort_unstable();
            names.dedup();
            assert_eq!(names.len(), count, "{names:?}");
        }

        // The joints: the `world` weld first, then one per link in the
        // resolved order, none of them carrying a `<pose>` and no `<xyz>`
        // carrying an `expressed_in` — SDF's defaults are ADR-0004's
        // conventions and writing them would be writing zeros (ADR-0016 §2).
        let joints: Vec<_> = model.kids("joint").collect();
        let names: Vec<&str> = joints.iter().map(|j| j.attr("name").unwrap()).collect();
        assert_eq!(
            names,
            [
                "world_joint",
                "upper_joint",
                "slider_joint",
                "wheel_joint",
                "tip_joint"
            ]
        );
        for joint in &joints {
            assert_eq!(joint.child("pose"), None, "{}", joint.attr("name").unwrap());
            if let Some(axis) = joint.child("axis") {
                assert_eq!(axis.child("xyz").unwrap().attr("expressed_in"), None);
            }
        }
        // All four kinds by SDF's own names, so none is approximated.
        let kinds: Vec<&str> = joints.iter().map(|j| j.attr("type").unwrap()).collect();
        assert_eq!(
            kinds,
            ["fixed", "revolute", "prismatic", "continuous", "fixed"]
        );
        // A continuous joint has an axis and no `<limit>`: SDF's ±inf
        // default is what "unlimited" means, and `0 0` would be a locked
        // joint (ADR-0016 §3).
        let wheel = joints[3];
        assert!(wheel.child("axis").unwrap().child("limit").is_none());
        // The mimic is SDF 1.11's own element, not a comment (ADR-0016 §1).
        let mimic = joints[2]
            .child("axis")
            .unwrap()
            .child("mimic")
            .expect("the slider follows the hinge");
        assert_eq!(mimic.attr("joint"), Some("upper_joint"));
        assert_eq!(
            mimic
                .children
                .iter()
                .map(|c| c.tag.as_str())
                .collect::<Vec<_>>(),
            ["multiplier", "offset", "reference"]
        );
        // Two frames, each attached to its link (ADR-0012's third spelling).
        let frames: Vec<_> = model.kids("frame").collect();
        assert_eq!(
            frames
                .iter()
                .map(|f| (f.attr("name").unwrap(), f.attr("attached_to").unwrap()))
                .collect::<Vec<_>>(),
            [("camera_mount", "base_link"), ("tcp", "tip")]
        );
        // No dummy link and no fixed joint per frame, the way URDF needs
        // them: the five links and five joints above are all there are.
        assert_eq!(model.kids("link").count(), 5);
    }

