//! The SDF writer (ADR-0016, docs/02-data-model.md §Format mapping): the
//! third dumb serialiser of one `ResolvedRobot`, and the one that has to
//! apologise least. SDF's own defaults are riggen's conventions — a
//! joint's pose is the child link frame (ADR-0004), an axis is expressed
//! in the joint frame — so a link's `<pose relative_to>` *is*
//! `ResolvedJoint::origin` and nothing is composed on the way out.

use std::path::Path;

use riggen_core::{ActuatorSpec, JointKind, Pose, Primitive};

use crate::resolve::{ExportOptions, MeshPathStyle, ResolvedGeom, ResolvedJoint, ResolvedRobot};
use crate::xml::{Xml, num, pose6, vec3};

/// The spec version we write. 1.11 is the first with `<axis><mimic>`, and
/// `libsdformat14` — what Gazebo Harmonic ships — reads it (ADR-0016 §1).
pub const VERSION: &str = "1.11";

/// `dir` is where the export lands: `MeshPathStyle::Absolute` names the
/// written mesh files by their absolute path.
pub fn write(robot: &ResolvedRobot, options: &ExportOptions, dir: &Path) -> String {
    let mut x = Xml::new();
    x.open("sdf", &[("version", VERSION.into())]);
    x.open("model", &[("name", robot.name.clone())]);
    x.comment("Generated by riggen. Meshes are in meters (ADR-0008).");
    for (i, link) in robot.links.iter().enumerate() {
        x.open("link", &[("name", link.name.clone())]);
        // The pose graph, spelled as the tree it came from: a link sits at
        // its parent joint's origin in its parent link's frame, and the
        // root sits at the model origin and says nothing.
        if let Some(joint) = robot.parent_joint(i) {
            x.text(
                "pose",
                &[("relative_to", robot.links[joint.parent].name.clone())],
                &pose6(&joint.origin),
            );
        }
        if let Some(inertial) = &link.inertial {
            let m = &inertial.inertia;
            x.open("inertial", &[]);
            // The CoM, in link axes: the tensor is about the CoM and
            // aligned with the link, so the pose carries no rotation.
            x.text("pose", &[], &pose6(&Pose::from_translation(inertial.com)));
            x.text("mass", &[], &num(inertial.mass));
            x.open("inertia", &[]);
            for (tag, value) in [
                ("ixx", m.x_axis.x),
                ("ixy", m.y_axis.x),
                ("ixz", m.z_axis.x),
                ("iyy", m.y_axis.y),
                ("iyz", m.z_axis.y),
                ("izz", m.z_axis.z),
            ] {
                x.text(tag, &[], &num(value));
            }
            x.close("inertia");
            x.close("inertial");
        }
        // SDF names every visual and collision, and the names have to be
        // unique inside the link, so they are the link's own plus the
        // index the resolver put them in.
        for (i, geom) in link.visuals.iter().enumerate() {
            write_geom(&mut x, "visual", &link.name, i, geom, options, dir);
        }
        for (i, geom) in link.collisions.iter().enumerate() {
            write_geom(&mut x, "collision", &link.name, i, geom, options, dir);
        }
        x.close("link");
    }
    // A fixed base is a fixed joint to SDF's reserved `world` frame; a
    // floating one is a model with nothing holding it, which is what MJCF
    // spells `<freejoint/>` (ADR-0016 §3).
    if !robot.floating_base
        && let Some(root) = robot.links.first()
    {
        x.open(
            "joint",
            &[("name", "world_joint".into()), ("type", "fixed".into())],
        );
        x.text("parent", &[], "world");
        x.text("child", &[], &root.name);
        x.close("joint");
    }
    for joint in &robot.joints {
        write_joint(&mut x, robot, joint);
    }
    // A named frame is SDF's own `<frame>` (ADR-0012's third spelling):
    // `<pose>`'s default `relative_to` is the `attached_to` frame, so the
    // pose goes out in the link frame verbatim.
    let sites = robot
        .links
        .iter()
        .flat_map(|l| l.sites.iter().map(move |s| (l, s)));
    for (link, site) in sites {
        x.open(
            "frame",
            &[
                ("name", site.name.clone()),
                ("attached_to", link.name.clone()),
            ],
        );
        x.text("pose", &[], &pose6(&site.pose));
        x.close("frame");
    }
    x.close("model");
    x.close("sdf");
    x.finish()
}

fn write_joint(x: &mut Xml, robot: &ResolvedRobot, j: &ResolvedJoint) {
    // All four kinds are SDF's own words, so none is approximated.
    let kind = match j.kind {
        JointKind::Fixed => "fixed",
        JointKind::Revolute => "revolute",
        JointKind::Continuous => "continuous",
        JointKind::Prismatic => "prismatic",
    };
    x.open("joint", &[("name", j.name.clone()), ("type", kind.into())]);
    x.text("parent", &[], &robot.links[j.parent].name);
    x.text("child", &[], &robot.links[j.child].name);
    // No `<pose>`: SDF already expresses a joint in the child link frame,
    // which is riggen's joint frame (ADR-0004), so the default is the
    // convention and writing it would be writing zeros (ADR-0016 §2).
    if j.kind.is_movable() {
        x.open("axis", &[]);
        // No `expressed_in` either: `<xyz>`'s default frame is the joint
        // frame, the same child link frame `ResolvedJoint::axis` is in.
        x.text("xyz", &[], &vec3(j.axis));
        if let Some(l) = &j.limits {
            x.open("limit", &[]);
            x.text("lower", &[], &num(l.lower));
            x.text("upper", &[], &num(l.upper));
            // A zero effort or velocity is the *unfilled* value (ADR-0014),
            // and SDF's default for both is infinity while a literal 0 is
            // a joint that can exert nothing — so it is omitted, as MJCF
            // omits `forcerange` and `ctrlrange`.
            if l.effort != 0.0 {
                x.text("effort", &[], &num(l.effort));
            }
            if l.velocity != 0.0 {
                x.text("velocity", &[], &num(l.velocity));
            }
            x.close("limit");
        }
        let d = &j.dynamics;
        if d.damping != 0.0 || d.friction != 0.0 {
            x.open("dynamics", &[]);
            x.text("damping", &[], &num(d.damping));
            x.text("friction", &[], &num(d.friction));
            x.close("dynamics");
        }
        // SDF 1.11's own coupled DoF, and the reason we write 1.11 at all
        // (ADR-0016 §1): `follower = multiplier·(leader − reference) +
        // offset` is ADR-0013's rule with `reference` at zero, and all
        // three numbers are written so the file states the whole thing.
        if let Some(m) = &j.mimic {
            x.open("mimic", &[("joint", robot.joints[m.joint].name.clone())]);
            x.text("multiplier", &[], &num(m.multiplier));
            x.text("offset", &[], &num(m.offset));
            x.text("reference", &[], &num(0.0));
            x.close("mimic");
        }
        x.close("axis");
    }
    if j.dynamics.armature != 0.0 {
        x.comment(&format!(
            "joint {}: armature {} is an MJCF property; not written",
            j.name,
            num(j.dynamics.armature)
        ));
    }
    // SDF has no actuator either. Gazebo drives a joint through a
    // `<plugin>` naming a C++ class, a shared library and a version of
    // Gazebo — a simulator configuration, not a robot description — so
    // ADR-0014's URDF reasoning applies word for word (ADR-0016 §5).
    if let Some(a) = j.actuator {
        let gains = match a {
            ActuatorSpec::Position { kp, kv } => format!("kp {} kv {}", num(kp), num(kv)),
            ActuatorSpec::Velocity { kv } => format!("kv {}", num(kv)),
            ActuatorSpec::Motor { gear } => format!("gear {}", num(gear)),
        };
        x.comment(&format!(
            "joint {}: a {} actuator ({gains}) is an MJCF property; not written",
            j.name,
            a.kind_name(),
        ));
    }
    x.close("joint");
}

fn write_geom(
    x: &mut Xml,
    tag: &str,
    link: &str,
    index: usize,
    geom: &ResolvedGeom,
    options: &ExportOptions,
    dir: &Path,
) {
    x.open(tag, &[("name", format!("{link}_{tag}_{index}"))]);
    match geom {
        ResolvedGeom::Mesh { name, pose, .. } => {
            x.text("pose", &[], &pose6(pose));
            x.open("geometry", &[]);
            x.open("mesh", &[]);
            x.text("uri", &[], &mesh_uri(name, options, dir));
            x.close("mesh");
            x.close("geometry");
        }
        // Every primitive riggen has, SDF has — including the capsule,
        // which URDF writes as a cylinder plus an apology (ADR-0016 §3).
        // SDF's capsule `<length>` is its cylindrical part, exactly ours.
        ResolvedGeom::Primitive(p) => {
            let (pose, shape, fields): (&Pose, &str, Vec<(&str, String)>) = match p {
                Primitive::Box { pose, size } => (pose, "box", vec![("size", vec3(*size))]),
                Primitive::Cylinder {
                    pose,
                    radius,
                    length,
                } => (
                    pose,
                    "cylinder",
                    vec![("radius", num(*radius)), ("length", num(*length))],
                ),
                Primitive::Sphere { pose, radius } => {
                    (pose, "sphere", vec![("radius", num(*radius))])
                }
                Primitive::Capsule {
                    pose,
                    radius,
                    length,
                } => (
                    pose,
                    "capsule",
                    vec![("radius", num(*radius)), ("length", num(*length))],
                ),
            };
            x.text("pose", &[], &pose6(pose));
            x.open("geometry", &[]);
            x.open(shape, &[]);
            for (field, value) in fields {
                x.text(field, &[], &value);
            }
            x.close(shape);
            x.close("geometry");
        }
    }
    x.close(tag);
}

/// The `<mesh><uri>` for `stem` under `options.mesh_paths` (ADR-0016 §4):
/// SDF's `model://` is URDF's `package://`, so the one dialog control
/// means one thing in both files.
pub fn mesh_uri(stem: &str, options: &ExportOptions, dir: &Path) -> String {
    let relative = format!("meshes/{stem}.stl");
    match &options.mesh_paths {
        MeshPathStyle::Relative => relative,
        MeshPathStyle::Package(package) => format!("model://{package}/{relative}"),
        MeshPathStyle::Absolute => {
            let path = dir.join(&relative);
            let path = riggen_core::absolute(&path).unwrap_or(path);
            format!("file://{}", path.display())
        }
    }
}

