//! The URDF writer (docs/02-data-model.md §Format mapping, ADR-0004): a
//! flat list of `<link>`s and `<joint>`s in the resolved order, `<origin
//! xyz rpy>` from `Pose::to_xyz_rpy`, `<inertia>` about the CoM in link
//! axes, `<mesh filename>` in the chosen [`MeshPathStyle`]. Verified by
//! the round-trip: `urdf-rs` parses this back and an independent FK from
//! the parsed numbers agrees with `riggen_core::fk`.

use std::path::Path;

use riggen_core::{JointKind, Pose, Primitive};

use crate::resolve::{ExportOptions, MeshPathStyle, ResolvedGeom, ResolvedJoint, ResolvedRobot};
use crate::xml::{Xml, num, vec3};

/// `dir` is where the export lands: `MeshPathStyle::Absolute` names the
/// written mesh files by their absolute path.
pub fn write(robot: &ResolvedRobot, options: &ExportOptions, dir: &Path) -> String {
    let mut x = Xml::new();
    x.open("robot", &[("name", robot.name.clone())]);
    x.comment("Generated by riggen. Meshes are in meters (ADR-0008).");
    for link in &robot.links {
        x.open("link", &[("name", link.name.clone())]);
        if let Some(i) = &link.inertial {
            let m = &i.inertia;
            x.open("inertial", &[]);
            x.empty("origin", &[("xyz", vec3(i.com)), ("rpy", "0 0 0".into())]);
            x.empty("mass", &[("value", num(i.mass))]);
            x.empty(
                "inertia",
                &[
                    ("ixx", num(m.x_axis.x)),
                    ("ixy", num(m.y_axis.x)),
                    ("ixz", num(m.z_axis.x)),
                    ("iyy", num(m.y_axis.y)),
                    ("iyz", num(m.z_axis.y)),
                    ("izz", num(m.z_axis.z)),
                ],
            );
            x.close("inertial");
        }
        for geom in &link.visuals {
            write_geom(&mut x, "visual", geom, options, dir);
        }
        for geom in &link.collisions {
            write_geom(&mut x, "collision", geom, options, dir);
        }
        x.close("link");
    }
    for joint in &robot.joints {
        write_joint(&mut x, robot, joint);
    }
    x.close("robot");
    x.finish()
}

fn write_joint(x: &mut Xml, robot: &ResolvedRobot, j: &ResolvedJoint) {
    let kind = match j.kind {
        JointKind::Fixed => "fixed",
        JointKind::Revolute => "revolute",
        JointKind::Continuous => "continuous",
        JointKind::Prismatic => "prismatic",
    };
    x.open("joint", &[("name", j.name.clone()), ("type", kind.into())]);
    x.empty("origin", &origin_attrs(&j.origin));
    x.empty("parent", &[("link", robot.links[j.parent].name.clone())]);
    x.empty("child", &[("link", robot.links[j.child].name.clone())]);
    if j.kind.is_movable() {
        x.empty("axis", &[("xyz", vec3(j.axis))]);
    }
    if let Some(l) = &j.limits {
        x.empty(
            "limit",
            &[
                ("lower", num(l.lower)),
                ("upper", num(l.upper)),
                ("effort", num(l.effort)),
                ("velocity", num(l.velocity)),
            ],
        );
    }
    let d = &j.dynamics;
    if d.damping != 0.0 || d.friction != 0.0 {
        x.empty(
            "dynamics",
            &[("damping", num(d.damping)), ("friction", num(d.friction))],
        );
    }
    if d.armature != 0.0 {
        x.comment(&format!(
            "joint {}: armature {} is an MJCF property; not written",
            j.name,
            num(d.armature)
        ));
    }
    x.close("joint");
}

fn write_geom(x: &mut Xml, tag: &str, geom: &ResolvedGeom, options: &ExportOptions, dir: &Path) {
    x.open(tag, &[]);
    match geom {
        ResolvedGeom::Mesh { name, pose, .. } => {
            x.empty("origin", &origin_attrs(pose));
            x.open("geometry", &[]);
            x.empty("mesh", &[("filename", mesh_filename(name, options, dir))]);
            x.close("geometry");
        }
        ResolvedGeom::Primitive(p) => {
            let (pose, tag, attrs): (&Pose, &str, Vec<(&str, String)>) = match p {
                Primitive::Box { pose, size } => (pose, "box", vec![("size", vec3(*size))]),
                Primitive::Cylinder {
                    pose,
                    radius,
                    length,
                } => (
                    pose,
                    "cylinder",
                    vec![("radius", num(*radius)), ("length", num(*length))],
                ),
                Primitive::Sphere { pose, radius } => {
                    (pose, "sphere", vec![("radius", num(*radius))])
                }
                Primitive::Capsule {
                    pose,
                    radius,
                    length,
                } => {
                    // URDF has no capsule: the cylinder of the same size,
                    // and a comment so nobody wonders where the caps went.
                    x.comment("capsule written as a cylinder: URDF has no capsule");
                    (
                        pose,
                        "cylinder",
                        vec![("radius", num(*radius)), ("length", num(*length))],
                    )
                }
            };
            x.empty("origin", &origin_attrs(pose));
            x.open("geometry", &[]);
            x.empty(tag, &attrs);
            x.close("geometry");
        }
    }
    x.close(tag);
}

/// The `<mesh filename>` for `stem` under `options.mesh_paths`.
pub fn mesh_filename(stem: &str, options: &ExportOptions, dir: &Path) -> String {
    let relative = format!("meshes/{stem}.stl");
    match &options.mesh_paths {
        MeshPathStyle::Relative => relative,
        MeshPathStyle::Package(package) => format!("package://{package}/{relative}"),
        MeshPathStyle::Absolute => {
            let path = dir.join(&relative);
            riggen_core::absolute(&path)
                .unwrap_or(path)
                .display()
                .to_string()
        }
    }
}

fn origin_attrs(pose: &Pose) -> Vec<(&'static str, String)> {
    let (xyz, rpy) = pose.to_xyz_rpy();
    vec![("xyz", vec3(xyz)), ("rpy", vec3(rpy))]
}

