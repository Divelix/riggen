    /// FK from the parsed URDF alone: `xyz rpy` and `axis` as urdf-rs hands
    /// them, glam matrices, no `Pose`, no `riggen_core::fk`. The URDF
    /// convention: `T_child = T_parent · Trans(xyz) · Rz(y)·Ry(p)·Rx(r) ·
    /// motion(axis, q)`.
    fn independent_fk(robot: &urdf_rs::Robot, q: &BTreeMap<&str, f64>) -> BTreeMap<String, DMat4> {
        let mut world: BTreeMap<String, DMat4> = BTreeMap::new();
        let parents: std::collections::BTreeSet<&str> = robot
            .joints
            .iter()
            .map(|j| j.parent.link.as_str())
            .collect();
        let children: std::collections::BTreeSet<&str> =
            robot.joints.iter().map(|j| j.child.link.as_str()).collect();
        let root = robot
            .links
            .iter()
            .map(|l| l.name.as_str())
            .find(|n| parents.contains(n) && !children.contains(n))
            .expect("one root");
        world.insert(root.to_owned(), DMat4::IDENTITY);
        // Joints are written parent-first, so one pass resolves them all.
        for j in &robot.joints {
            let parent = world[&j.parent.link];
            let [x, y, z] = *j.origin.xyz;
            let [r, p, yw] = *j.origin.rpy;
            let rot =
                DMat3::from_rotation_z(yw) * DMat3::from_rotation_y(p) * DMat3::from_rotation_x(r);
            let origin = DMat4::from_translation(DVec3::new(x, y, z)) * DMat4::from_mat3(rot);
            let axis = DVec3::from_array(*j.axis.xyz).normalize();
            let qj = q.get(j.name.as_str()).copied().unwrap_or(0.0);
            let motion = match j.joint_type {
                urdf_rs::JointType::Revolute | urdf_rs::JointType::Continuous => {
                    DMat4::from_axis_angle(axis, qj)
                }
                urdf_rs::JointType::Prismatic => DMat4::from_translation(axis * qj),
                _ => DMat4::IDENTITY,
            };
            world.insert(j.child.link.clone(), parent * origin * motion);
        }
        world
    }

    #[test]
    fn round_trip_fk_agrees_on_a_grid() {
        let (robot, _) = riggen_core::load(&fixtures().join("arm/arm.riggen")).unwrap();
        let (store, errors) = MeshStore::load(&robot);
        assert!(errors.is_empty(), "{errors:?}");
        let resolved = crate::resolve(&robot, &store, &ExportOptions::default()).unwrap();
        let urdf = write(&resolved, &ExportOptions::default(), Path::new("."));
        let parsed = urdf_rs::read_from_string(&urdf).unwrap();

        let movable: Vec<_> = robot
            .joints
            .iter()
            .filter(|(_, j)| j.kind.is_movable())
            .collect();
        assert_eq!(movable.len(), 3);
        let fore = *robot
            .links
            .iter()
            .find(|(_, l)| l.name == "fore")
            .unwrap()
            .0;
        let grid = [-1.2, -0.4, 0.0, 0.7, 1.5];
        let mut compared = 0;
        for a in grid {
            for b in grid {
                for c in grid {
                    let values = [a, b, c];
                    let mut state = JointState::new();
                    let mut q = BTreeMap::new();
                    for ((id, joint), v) in movable.iter().zip(values) {
                        state.set(**id, v);
                        q.insert(joint.name.as_str(), v);
                    }
                    let ours = fk(&robot, &state)[&fore].to_mat4();
                    let theirs = independent_fk(&parsed, &q)["fore"];
                    let diff = (ours - theirs).to_cols_array();
                    let worst = diff.iter().fold(0.0f64, |m, v| m.max(v.abs()));
                    assert!(worst < 1e-9, "q = {values:?}: {worst:e}\n{ours}\n{theirs}");
                    compared += 1;
                }
            }
        }
        assert_eq!(compared, 125);
    }
